/** The SVG markup for an icon. */
export function icon(name, extraClass = '') {
  const rows = ICONS[name];
  if (!rows) return '';
  let rects = '';
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length; x++) if (row[x] === '#') rects += `<rect x="${x}" y="${y}" width="1" height="1"/>`;
  });
  return `<svg class="ico ${extraClass}" viewBox="0 0 8 8" aria-hidden="true" focusable="false" shape-rendering="crispEdges" fill="currentColor">${rects}</svg>`;
}

/** Put an icon in front of every element that has data-icon="name". */
export function decorate(root = document) {
  for (const el of root.querySelectorAll('[data-icon]')) {
    if (el.querySelector(':scope > .ico')) continue;
    el.insertAdjacentHTML('afterbegin', icon(el.dataset.icon));
  }
}
